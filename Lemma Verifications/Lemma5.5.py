OMEGA_K_MAX = 108

def coprime_weaker(a,b):
    fi_A = factorint(a)
    fi_B = factorint(b)
    for p in fi_A:
        if p in fi_B.keys() and p > 2:
            return False
    return True

def nextcoprimesquarefree_evens(y,coprime_to):
    i = 2
    while i > 0:
        fi = factorint(y + i)
        condition_met = [coprime_weaker(j,y+i) for j in coprime_to] 
        if max(fi.values()) == 1 and False not in condition_met:
            return y + i
        i += 2

def is_good(n,v):
    sf = 2 #the first nontrivial squarefree
    cpt = []
    while sf < n:
        if isprime(n-sf) == True:
            cpt.append(sf)
        if len(cpt) < v+1:
            sf = nextcoprimesquarefree_evens(sf, cpt)
        else:
            return True, cpt
    return False, cpt

def is_prime_times_power_of_two(n):
    while n % 2 == 0:
        n = n/2
    return isprime(n)

def issquarefree(y):
    fi = factorint(y)
    if max(fi.values()) == 1:
        return True
    else:
        return False

